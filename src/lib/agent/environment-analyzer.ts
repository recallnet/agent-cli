import fs from 'fs';
import path from 'path';
import dotenv from 'dotenv';
import chalk from 'chalk';

export interface EnvVariable {
  name: string;
  description: string;
  required: boolean;
  secret: boolean;
  value?: string;
  source?: 'env' | 'dotenv' | 'user-input';
}

export interface PluginEnvRequirement {
  pluginName: string;
  variables: EnvVariable[];
}

export interface EnvAnalysisResult {
  requiredVariables: EnvVariable[];
  missingVariables: EnvVariable[];
  availableVariables: EnvVariable[];
  pluginRequirements: PluginEnvRequirement[];
  isComplete: boolean;
}

